function extractUtilities(oldCss) {
    const puaIndex = oldCss.indexOf('/* Font Awesome uses the Unicode Private Use Area');
    if (puaIndex < 0) throw new Error('Cannot locate icon definitions in line-awesome-fa.css');
    return oldCss.slice(0, puaIndex)
        .replace(/^(?:\s*\/\*[\s\S]*?\*\/|\s*@import[^;]*;)+/, '')
        .trimEnd();
}

function faRules(groups, laGroups, uriFor, laUriFor) {
    let rules = '';
    for (const [target, groupNames] of groups) {
        rules += groupNames.map(n => '.fa-' + n).join(', ') + ' { --sv: url("' + uriFor(target) + '"); }\n';
    }
    for (const [target, groupNames] of laGroups) {
        rules += groupNames.map(n => '.fa-' + n).join(', ') + ' { --sv: url("' + laUriFor(target) + '"); }\n';
    }
    return rules;
}

function loadContext() {
    const tabler = resolveIconSet();
    const la = resolveLineAwesomeSet();
    const map = JSON.parse(readFileSync(mapUrl, 'utf8'));
    const oldCss = readFileSync(compatCssUrl, 'utf8');
    const iconsTs = readFileSync(iconsTsUrl, 'utf8');
    const fabSet = new Set([...iconsTs.match(/export type fabIconKey =([\s\S]*?);/)[1].matchAll(/"([^"]+)"/g)].map(m => m[1]));

    const tablerHas = (name) => !!tabler.icons[name] || !!tabler.aliases?.[name];
    const faCandidates = (name) => {
        const out = new Set([name]);
        if (name.endsWith('-o')) out.add(name.slice(0, -2));
        if (name.startsWith('thumbs-o-')) out.add('thumbs-' + name.slice(9));
        if (name.endsWith('-alt')) out.add(name.slice(0, -4));
        if (name.endsWith('-circle')) out.add('circle-' + name.slice(0, -7));
        return [...out];
    };
    const brandCandidates = (name) => {
        const out = new Set(['brand-' + name]);
        if (name.endsWith('-square')) out.add('brand-' + name.slice(0, -7));
        return [...out];
    };
    const match = (name) => {
        if (Object.prototype.hasOwnProperty.call(map, name)) {
            const target = map[name];
            if (target === '') return useLineAwesome;
            if (target === null || target === undefined) return null;
            if (!tablerHas(target)) throw new Error(`tabler-fa-map.json maps "${name}" to "${target}" which is not a valid Tabler icon`);
            return target;
        }
        if (fabSet.has(name)) {
            for (const c of brandCandidates(name)) if (tablerHas(c)) return c;
            return null;
        }
        for (const c of faCandidates(name)) if (tablerHas(c)) return c;
        return null;
    };

    // collect fa class names in original css order
    const names = [];
    const seen = new Set();
    for (const m of oldCss.matchAll(/^\.fa(?:\.fa)?-([a-z0-9-]+):before/gm)) {
        if (!seen.has(m[1])) { seen.add(m[1]); names.push(m[1]); }
    }

    const uriFor = (target) => {
        const css = getIconsCSS(tabler, [target], { iconSelector: '.x', varName: 'svg', mode: 'mask', format: 'compressed' });
        const mm = css.match(/--svg:url\("([^"]+)"\)/);
        if (!mm) throw new Error('Could not generate icon data for tabler:' + target);
        return strokeWidth === 2 ? mm[1] : mm[1].replace(/stroke-width='2'/g, "stroke-width='" + strokeWidth + "'");
    };

    const laResolve = (name) => la.icons[name] ? name : (la.aliases?.[name]?.parent ?? null);
    const laUriFor = (target) => {
        const css = getIconsCSS(la, [target], { iconSelector: '.x', varName: 'svg', mode: 'mask', format: 'compressed' });
        const mm = css.match(/--svg:url\("([^"]+)"\)/);
        if (!mm) throw new Error('Could not generate icon data for line-awesome:' + target);
        return mm[1];
    };

    const groups = new Map();
    const laGroups = new Map();
    for (const name of names) {
        const target = match(name);
        if (target === useLineAwesome) {
            const laName = laResolve(name);
            if (laName)
                (laGroups.get(laName) ?? laGroups.set(laName, []).get(laName)).push(name);
            continue;
        }
        if (!target) continue;
        (groups.get(target) ?? groups.set(target, []).get(target)).push(name);
    }

    return { oldCss, names, groups, laGroups, match, uriFor, laResolve, laUriFor };
}

export function buildTablerFaSubset() {
    const { oldCss, names, groups, laGroups, uriFor, laUriFor } = loadContext();

    const rules = faRules(groups, laGroups, uriFor, laUriFor);

    const matched = [...groups.values()].reduce((a, g) => a + g.length, 0);
    const laMatched = [...laGroups.values()].reduce((a, g) => a + g.length, 0);
    const omitted = names.length - matched - laMatched;
    console.log(`tabler-fa-subset: ${matched} tabler + ${laMatched} line-awesome fallback = ${matched + laMatched}/${names.length} mapped, ${omitted} omitted.`);

    return subsetHeader + '@import "./tabler-serenity-icons.css";\n\n' + extractUtilities(oldCss) + '\n' + maskBase + rules;
}

export function buildTablerIconsSvg() {
    const { oldCss, groups, laGroups, uriFor, laUriFor } = loadContext();
    const tabler = resolveIconSet();
    const allNames = [...new Set([...Object.keys(tabler.icons), ...Object.keys(tabler.aliases ?? {})])].sort();

    // Share one rule per unique SVG between the .ti-<name> class and any .fa-*
    // class mapping to the same icon (aliases dedupe here as well), so no data
    // URI is emitted twice.
    const byUri = new Map();
    const add = (uri, selector) => {
        let selectors = byUri.get(uri);
        if (!selectors) byUri.set(uri, selectors = []);
        selectors.push(selector);
    };

    for (const name of allNames) add(uriFor(name), '.ti-' + name);
    for (const [target, groupNames] of groups)
        for (const n of groupNames) add(uriFor(target), '.fa-' + n);
    for (const [target, groupNames] of laGroups)
        for (const n of groupNames) add(laUriFor(target), '.fa-' + n);

    let rules = '';
    for (const [uri, selectors] of byUri)
        rules += selectors.join(', ') + ' { --sv: url("' + uri + '"); }\n';

    const faCount = [...groups.values()].reduce((a, g) => a + g.length, 0);
    const laCount = [...laGroups.values()].reduce((a, g) => a + g.length, 0);
    console.log(`tabler-icons-svg: ${allNames.length} .ti-* icon classes + ${faCount} tabler / ${laCount} line-awesome fa mappings = ${byUri.size} shared icon rules.`);

    return iconsSvgHeader + '@import "./tabler-serenity-icons.css";\n\n' + extractUtilities(oldCss) + '\n' + iconsMaskBase + rules;
}

export function buildTablerFaShim() {
    const { oldCss, names, match } = loadContext();
    const tabler = resolveIconSet();
    const { codepoints, family } = loadWebfont();
    if (!codepoints.size)
        throw new Error('@tabler/icons-webfont CSS not found - run `pnpm install` in packages/assets');

    // Resolve an alias target (name not present as its own webfont class) to
    // its parent's codepoint.
    const cpFor = (name) => codepoints.get(name)
        ?? (tabler.aliases?.[name]?.parent ? codepoints.get(tabler.aliases[name].parent) : undefined);

    const byCodepoint = new Map();
    let mapped = 0, lineAwesome = 0, noCodepoint = 0;
    const missingNames = [];
    for (const name of names) {
        const target = match(name);
        if (target === useLineAwesome) { lineAwesome++; continue; }
        if (!target) continue;
        const cp = cpFor(target);
        if (!cp) { noCodepoint++; missingNames.push(name + '->' + target); continue; }
        let selectors = byCodepoint.get(cp);
        if (!selectors) byCodepoint.set(cp, selectors = []);
        selectors.push('.fa-' + name);
        mapped++;
    }

    let rules = '';
    for (const [cp, selectors] of byCodepoint)
        rules += selectors.map(s => s + ':before').join(', ') + ' { content: "' + cp + '"; }\n';

    // Utility classes (fa-lg, fa-2x, stacking, ...) only. The Line Awesome icon
    // definitions and fonts further down in the file are intentionally ignored.
    // No fonts are declared here; the family defaults to the standard webfont
    // but can be pointed at another weight (e.g. via tabler-icons-300.css).
    let utilities = extractUtilities(oldCss);

    const fontFamily = `    font-family: var(--tabler-icons-font, "${family}");\n`;
    const smoothingIndex = utilities.indexOf('-moz-osx-font-smoothing');
    if (smoothingIndex < 0) {
        utilities = `.fa,\n.fas,\n.far,\n.fal,\n.fad,\n.fab {\n${fontFamily}}\n\n` + utilities;
    }
    else {
        const lineStart = utilities.lastIndexOf('\n', smoothingIndex) + 1;
        utilities = utilities.slice(0, lineStart) + fontFamily + utilities.slice(lineStart);
    }

    console.log(`tabler-fa-shim: ${mapped} fa classes -> ${byCodepoint.size} tabler glyphs, family "${family}" (${lineAwesome} line-awesome, ${noCodepoint} without codepoint skipped).`);
    if (missingNames.length) console.log('  no codepoint:', missingNames.join(', '));

    return faShimHeader + utilities + '\n' + rules;
}

