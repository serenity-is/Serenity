import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { beforeAll, describe, expect, it } from "vitest";

import { bundleDts, findConfigFrom } from "../src/index";

/** Most specs only care about the bundle text. */
function bundleDtsText(options: Parameters<typeof bundleDts>[0]): string {
    return bundleDts(options).dts;
}
import { ensureFixtureNodeModules } from "./setup";

const here = dirname(fileURLToPath(import.meta.url));
const basic = join(here, "fixtures", "basic");
const entry = join(basic, "src", "entry.ts");
const project = join(basic, "tsconfig.json");

const require = createRequire(import.meta.url);

function tscPath(): string {
    const typescriptDir = dirname(require.resolve("typescript/package.json"));
    return join(typescriptDir, "bin", "tsc");
}

/** Compiles the bundle with the TS 7 beta compiler to prove it is valid. */
function tscCheck(bundleText: string): void {
    const temp = mkdtempSync(join(tmpdir(), "dtsbundler-"));
    try {
        mkdirSync(join(temp, "node_modules"), { recursive: true });
        cpSync(join(basic, "node_modules", "ext-lib"), join(temp, "node_modules", "ext-lib"), { recursive: true });
        writeFileSync(join(temp, "bundle.d.ts"), bundleText + "\n");
        writeFileSync(join(temp, "tsconfig.json"), JSON.stringify({
            compilerOptions: {
                target: "esnext",
                module: "esnext",
                moduleResolution: "bundler",
                strict: true,
                noEmit: true,
                skipLibCheck: true,
            },
            files: ["bundle.d.ts"],
        }));
        execFileSync(process.execPath, [tscPath(), "-p", join(temp, "tsconfig.json")], { stdio: "pipe" });
    }
    finally {
        rmSync(temp, { recursive: true, force: true });
    }
}

describe("bundleDts", () => {
    beforeAll(() => {
        ensureFixtureNodeModules();
    });

    it("bundles a .ts entry end-to-end", () => {
        const result = bundleDtsText({ entry, project });

        // no banner, ever
        expect(result).not.toContain("Generated by");

        // external library kept as an import
        expect(result).toContain("import { External, ExternalDetail } from 'ext-lib';");

        // name collision between two local `Helper` declarations resolved via rename
        expect(result).toMatch(/^interface Helper2[^A-Za-z0-9_]/m);

        // the entry re-export is preserved
        expect(result).toMatch(/\bTypeA as LocalTypeA\b/);

        // unreferenced exported helper is tree-shaken
        expect(result).not.toContain("makeA");
    });

    it("never emits a banner comment", () => {
        const result = bundleDtsText({ entry, project });
        expect(result).not.toContain("Generated by");
        // imports come first, documentation is kept on the declarations
        expect(result.startsWith("import ")).toBe(true);
        expect(result).toContain("export {}");
    });

    it("exports exactly what the entry exports, by default", () => {
        const result = bundleDtsText({ entry, project });

        // directly-exported declarations keep their export keyword
        expect(result).toContain("export declare class Widget");
        expect(result).toContain("export interface PublicApi");
        expect(result).toContain("export interface Helper"); // re-exported via export *

        // referenced-only declarations stay in the bundle without the keyword
        // (Helper2 is the renamed collision one)
        expect(result).not.toMatch(/^export interface Helper2[^A-Za-z0-9_]/m);
        expect(result).toContain("interface Helper2");
    });

    it("honors exportReferencedTypes=true", () => {
        const result = bundleDtsText({ entry, project, exportReferencedTypes: true });

        // the same referenced-only declaration now becomes importable
        expect(result).toMatch(/^export interface Helper2[^A-Za-z0-9_]/m);
    });

    it("emits `declare` for referenced value declarations that lose `export`", () => {
        const result = bundleDtsText({ entry, project });

        // values referenced by the public API but not exported by the entry
        expect(result).toContain("declare const helperSymbol: unique symbol;");
        expect(result).toContain("declare namespace InternalNamespace {");
        expect(result).toContain("declare abstract class InternalBase {");

        // and they must not accidentally stay exported
        expect(result).not.toContain("export declare const helperSymbol");
        expect(result).not.toContain("export declare namespace InternalNamespace");
        expect(result).not.toContain("export declare abstract class InternalBase");
    });

    it("preserves JSDoc comments (top-level and members)", () => {
        const result = bundleDtsText({ entry, project });

        expect(result).toContain("/** The public API of the fixture. */");
        expect(result).toContain("/** A widget that holds the API. */");
        expect(result).toContain("/** Extra info. */");
        expect(result).toContain("/** The identifier. */");
        expect(result).toContain("@link Helper");
    });

    it("keeps the source indentation", () => {
        const result = bundleDtsText({ entry, project });

        // members keep the 4-space indentation of the declaration file
        expect(result).toMatch(/^ {4}\/\*\* Extra info\. \*\/$/m);

        // no top-level statement may keep the indentation of the block it came from
        // (members of `declare global` / `declare module` blocks are legitimately indented)
        let depth = 0;
        for (const line of result.split("\n")) {
            if (depth === 0 && /^[ \t]+(?:export )?(?:interface|type|class|declare|namespace|function|abstract)\b/.test(line)) {
                throw new Error(`top-level statement is indented: ${line}`);
            }
            depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
        }
        expect(depth).toBe(0);
    });

    describe("augmentations (inlined by default)", () => {
        it("includes external `declare module` augmentations by default", () => {
            const result = bundleDtsText({ entry, project });

            expect(result).toContain('declare module \'ext-lib\' {');
            expect(result).toContain("Added to the external module");
        });

        it("includes `declare global` blocks by default", () => {
            const result = bundleDtsText({ entry, project });

            expect(result).toContain("declare global {");
            expect(result).toContain("augmentedGlobal");
        });

        it("can be turned off", () => {
            const result = bundleDtsText({
                entry,
                project,
                inlineDeclareExternals: false,
                inlineDeclareGlobals: false,
            });

            expect(result).not.toContain('declare module \'ext-lib\'');
            expect(result).not.toContain("declare global {");
            // the rest of the bundle is unaffected
            expect(result).toContain("export interface PublicApi");
        });
    });

    it("rewrites `import(\"pkg\").Type` to the imported name", () => {
        const result = bundleDtsText({ entry, project });

        // generated code spells external references this way; the bundle already has the
        // import, so the inline specifier would only duplicate it
        expect(result).not.toContain('import(\'ext-lib\').ExternalDetail');
        expect(result).toContain("detail: ExternalDetail;");
        expect(result).toContain("nested: Array<ExternalDetail>;");
        expect(result).toContain("import { External, ExternalDetail } from 'ext-lib';");

        // same for a module that is inlined instead of imported
        expect(result).not.toContain('import(\'./internal\').Helper2Probe');
        expect(result).toContain("inlined: Helper2Probe;");
    });

    it("keeps `import(\"pkg\")` forms it cannot name", () => {
        const result = bundleDtsText({ entry, project });

        // `default` and qualified names have no equivalent bare identifier
        expect(result).not.toContain("import('ext-lib').default");
    });

    it("promotes relative `declare module` augmentations and keeps them exported", () => {
        const result = bundleDtsText({ entry, project });

        // the augmentation of a sibling module cannot survive bundling verbatim
        expect(result).not.toContain("declare module './internal'");
        expect(result).toContain("Added by the augmentation");

        // `TypeB` is exported by the entry, so both its declaration and the promoted
        // augmentation have to carry `export` (they merge in the bundle)
        const typeBDeclarations = result.split("\n").filter((line) => /^(?:export )?interface TypeB\b/.test(line));
        expect(typeBDeclarations).toHaveLength(2);
        expect(typeBDeclarations.every((line) => line.startsWith("export "))).toBe(true);
    });

    it("produces a bundle that compiles with tsc", () => {
        expect(tscCheck(bundleDtsText({ entry, project }))).toBeUndefined();
        expect(tscCheck(bundleDtsText({ entry, project, exportReferencedTypes: false }))).toBeUndefined();
    });

    describe("findConfigFrom", () => {
        it("finds the nearest tsconfig.json above the entry", () => {
            expect(findConfigFrom(entry)).toBe(project);
        });

        it("throws when there is no tsconfig.json", () => {
            const dir = mkdtempSync(join(tmpdir(), "dtsbundler-noconfig-"));
            try {
                expect(() => findConfigFrom(join(dir, "entry.ts"))).toThrow(/Cannot find tsconfig\.json/);
            }
            finally {
                rmSync(dir, { recursive: true, force: true });
            }
        });
    });

    describe("output file", () => {
        it("writes the bundle and reports it", () => {
            const outFile = join(mkdtempSync(join(tmpdir(), "dtsbundler-out-")), "nested", "index.d.ts");
            try {
                const result = bundleDts({ entry, project, outFile });

                expect(result.written).toBe(true);
                expect(result.outFile).toBe(resolve(outFile));
                expect(readFileSync(outFile, "utf8")).toBe(result.dts + "\n");
            }
            finally {
                rmSync(dirname(outFile), { recursive: true, force: true });
            }
        });

        it("does not touch the file when the content is unchanged", () => {
            const dir = mkdtempSync(join(tmpdir(), "dtsbundler-out-"));
            const outFile = join(dir, "index.d.ts");
            try {
                const first = bundleDts({ entry, project, outFile });
                const before = statSync(outFile).mtimeMs;
                const second = bundleDts({ entry, project, outFile });

                expect(first.written).toBe(true);
                expect(second.written).toBe(false);
                // same text, untouched file
                expect(second.dts).toBe(first.dts);
                expect(statSync(outFile).mtimeMs).toBe(before);
            }
            finally {
                rmSync(dir, { recursive: true, force: true });
            }
        });

        it("rewrites the file when the content changes", () => {
            const dir = mkdtempSync(join(tmpdir(), "dtsbundler-out-"));
            const outFile = join(dir, "index.d.ts");
            try {
                writeFileSync(outFile, "// stale\n");
                const result = bundleDts({ entry, project, outFile });

                expect(result.written).toBe(true);
                expect(readFileSync(outFile, "utf8")).toBe(result.dts + "\n");
            }
            finally {
                rmSync(dir, { recursive: true, force: true });
            }
        });

        it("reports per-stage timings", () => {
            const result = bundleDts({ entry, project });

            expect(result.outFile).toBeUndefined();
            expect(result.written).toBe(false);
            expect(result.timings.compile).toBeGreaterThanOrEqual(0);
            expect(result.timings.bundle).toBeGreaterThanOrEqual(0);
            expect(Number.isInteger(result.timings.compile)).toBe(true);
            expect(Number.isInteger(result.timings.bundle)).toBe(true);
        });
    });

    describe("self-bundle (what `pnpm dts` publishes)", () => {
        const selfEntry = join(here, "..", "src", "index.ts");
        const selfProject = join(here, "..", "tsconfig.json");

        it("bundles the package's own declarations", () => {
            const result = bundleDtsText({
                entry: selfEntry,
                project: selfProject,
            });

            // the whole public API, with its documentation
            expect(result).toContain("export interface DtsBundlerOptions {");
            expect(result).toContain("export declare function bundleDts(options: DtsBundlerOptions): BundleResult;");
            expect(result).toContain("export interface BundleResult {");
            expect(result).toContain("export declare function findConfigFrom(entry: string): string;");
            expect(result).toContain("Bundles the entry point's declaration files into a single `.d.ts` string.");
            expect(result.trimEnd().endsWith("export {};")).toBe(true);

            // internals must not leak into the published types
            expect(result).not.toContain("BundleStageOptions");
            expect(result).not.toContain("CompiledDts");
        });
    });
});