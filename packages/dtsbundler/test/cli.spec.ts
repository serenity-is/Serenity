import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import { afterAll, beforeAll, describe, expect, it } from 'vitest';

const here = path.dirname(fileURLToPath(import.meta.url));
const cliPath = path.join(here, '..', 'dist', 'cli.js');
const fixtureRoot = path.join(here, 'fixtures', 'basic');

// the fixture's `ext-lib` resolves through `fixtures/basic/node_modules`, so outputs
// written below that folder also type-check (the CLI validates the output by default)
const outRoot = path.join(fixtureRoot, 'tmp-cli-tests');
const entryPath = path.join(outRoot, 'src', 'entry.ts');

function run(args: readonly string[], cwd: string = here) {
	const result = spawnSync(process.execPath, [cliPath, ...args], { encoding: 'utf8', cwd });
	return {
		code: result.status,
		stdout: result.stdout ?? '',
		stderr: result.stderr ?? '',
	};
}

/** Windows prints backslashes in paths, the assertions use forward slashes. */
const toPosix = (text: string) => text.replaceAll('\\', '/');

describe('cli', () => {
	beforeAll(() => {
		// work on copies so the convention tests cannot leave a stale .d.ts next to
		// the real fixture sources (it would shadow entry.ts on module resolution)
		mkdirSync(outRoot, { recursive: true });
		cpSync(path.join(fixtureRoot, 'src'), path.join(outRoot, 'src'), { recursive: true });

		// one folder per convention case: only the entry under test may exist
		const withEntry = (name: string, entryRelPath: string) => {
			const dir = path.join(outRoot, 'conventions', name);
			cpSync(path.join(fixtureRoot, 'src'), path.join(dir, 'src'), { recursive: true });
			const target = path.join(dir, entryRelPath);
			mkdirSync(path.dirname(target), { recursive: true });
			renameSync(path.join(dir, 'src', 'entry.ts'), target);
		};
		withEntry('src-entry', path.join('src', 'index.ts'));
		withEntry('root-entry', 'index.ts');
		withEntry('modules-entry', path.join('Modules', 'index.ts'));

		// ambiguous: both src/index.ts and index.ts exist
		withEntry('ambiguous', path.join('src', 'index.ts'));
		cpSync(path.join(fixtureRoot, 'src', 'entry.ts'), path.join(outRoot, 'conventions', 'ambiguous', 'index.ts'));

		// none of the conventional entries exist
		mkdirSync(path.join(outRoot, 'conventions', 'none', 'src'), { recursive: true });
	});

	afterAll(() => {
		rmSync(outRoot, { recursive: true, force: true });
	});

	it('prints the version', () => {
		const { code, stdout } = run(['--version']);
		const pkg = JSON.parse(readFileSync(path.join(here, '..', 'package.json'), 'utf8')) as { version: string };

		expect(code).toBe(0);
		expect(stdout.trim()).toBe(pkg.version);
	});

	it('prints usage on --help', () => {
		const { code, stdout } = run(['--help']);

		expect(code).toBe(0);
		expect(stdout).toContain('Usage: dtsbundler [entry] [options]');
		expect(stdout).toContain('--no-inline-declare-global');
		expect(stdout).toContain('they are included by default');
		expect(stdout).toContain('entry   src/index.ts');
		expect(stdout).toContain('output  dist/index.d.ts');
	});

	it('writes the bundle to --out-file', () => {
		const outFile = path.join(outRoot, 'entry.d.ts');
		const { code, stdout, stderr } = run([entryPath, '-o', outFile]);

		expect(stderr).toBe('');
		expect(code).toBe(0);
		expect(stdout).toContain('Writing');

		const dts = readFileSync(outFile, 'utf8');
		expect(dts).toContain('export interface TypeA');
		expect(dts).not.toContain('Generated by');
	});

	it('writes dist/index.d.ts when -o is omitted', () => {
		const cwd = path.join(outRoot, 'conventions', 'src-entry');
		const outFile = path.join(cwd, 'dist', 'index.d.ts');
		const { code, stdout } = run([], cwd);

		expect(code).toBe(0);
		expect(stdout).toContain('Writing');
		expect(existsSync(outFile)).toBe(true);
		expect(readFileSync(outFile, 'utf8')).toContain('export interface TypeA');
	});

	it('finds the entry by convention: src/index.ts', () => {
		const cwd = path.join(outRoot, 'conventions', 'src-entry');
		const { code, stdout } = run(['--no-check'], cwd);

		expect(code).toBe(0);
		expect(toPosix(stdout)).toContain('src/index.ts');
	});

	it('finds the entry by convention: index.ts', () => {
		const cwd = path.join(outRoot, 'conventions', 'root-entry');
		const { code, stdout } = run(['--no-check'], cwd);

		expect(code).toBe(0);
		expect(toPosix(stdout)).toContain('Writing index.ts');
	});

	it('finds the entry by convention: Modules/index.ts', () => {
		const cwd = path.join(outRoot, 'conventions', 'modules-entry');
		const { code, stdout } = run(['--no-check'], cwd);

		expect(code).toBe(0);
		expect(toPosix(stdout)).toContain('Modules/index.ts');
	});

	it('refuses to guess when several conventional entries exist', () => {
		const cwd = path.join(outRoot, 'conventions', 'ambiguous');
		const { code, stderr } = run([], cwd);

		expect(code).toBe(1);
		expect(stderr).toContain('more than one possible entry file');
		expect(stderr).toContain('src/index.ts, index.ts');
	});

	it('explains when no conventional entry exists', () => {
		const cwd = path.join(outRoot, 'conventions', 'none');
		const { code, stderr } = run([], cwd);

		expect(code).toBe(1);
		expect(stderr).toContain('Cannot find an entry file');
		expect(stderr).toContain('Pass the input file explicitly');
	});

	it('rejects an explicit entry that does not exist', () => {
		const { code, stderr } = run(['nope.ts']);

		expect(code).toBe(1);
		expect(stderr).toContain('Input file "nope.ts" does not exist');
	});

	it('reports write status and per-stage timings', () => {
		const outFile = path.join(outRoot, 'timings.d.ts');

		const first = run([entryPath, '-o', outFile]);
		expect(first.code).toBe(0);
		expect(first.stdout).toMatch(/^Writing .* \(compile \d+ ms, bundle \d+ ms, check \d+ ms\)$/m);

		// identical output: nothing is written, and it says so
		const second = run([entryPath, '-o', outFile]);
		expect(second.code).toBe(0);
		expect(second.stdout).toMatch(/^Unchanged .* \(compile \d+ ms, bundle \d+ ms, check \d+ ms\)$/m);

		const skipped = run([entryPath, '-o', outFile, '--no-check']);
		expect(skipped.stdout).toContain('check skipped');
	});

	it('never writes a banner comment', () => {		const outFile = path.join(outRoot, 'banner.d.ts');
		const { code } = run([entryPath, '-o', outFile, '--banner']);

		// the option is gone, so it is an unknown flag rather than a silent no-op
		expect(code).toBe(1);

		const ok = run([entryPath, '-o', outFile]);
		expect(ok.code).toBe(0);
		expect(readFileSync(outFile, 'utf8')).not.toContain('Generated by');
	});

	it('accepts --flag=value and --no-flag forms', () => {
		const outFile = path.join(outRoot, 'eq.d.ts');
		const { code } = run([
			`--out-file=${outFile}`,
			'--project=' + path.join(fixtureRoot, 'tsconfig.json'),
			'--export-referenced-types=false',
			entryPath,
		]);
		expect(code).toBe(0);
		expect(readFileSync(outFile, 'utf8')).not.toMatch(/^export interface Helper2[^A-Za-z0-9_]/m);
	});

	it('validates the output by default and reports errors from --no-check runs', () => {
		// outside the fixture tree, `ext-lib` is not resolvable, so the check must fail
		const outFile = path.join(tmpdir(), 'dtsbundler-cli-check-test.d.ts');

		const failing = run([entryPath, '-o', outFile]);
		expect(failing.code).toBe(1);
		expect(failing.stderr).toContain('has errors');

		const passing = run([entryPath, '-o', outFile, '--no-check']);
		expect(passing.code).toBe(0);

		rmSync(outFile, { force: true });
	});

	it('rejects unknown and unsupported options', () => {
		const unknown = run([entryPath, '--bogus']);
		expect(unknown.code).toBe(1);
		expect(unknown.stderr).toContain('Unknown option "--bogus"');

		const unsupported = run([entryPath, '--sort']);
		expect(unsupported.code).toBe(1);
		expect(unsupported.stderr).toContain('not supported by @serenity-is/dtsbundler');
	});

	it('accepts --follow-symlinks and rejects the old inverted flag', () => {
		const followed = run([entryPath, '-o', path.join(outRoot, 'followed.d.ts'), '--follow-symlinks']);
		expect(followed.code).toBe(0);

		// not following symlinks is the default now, so the inverted flag is gone
		const old = run([entryPath, '--disable-symlinks-following']);
		expect(old.code).toBe(1);
		expect(old.stderr).toContain('Unknown option "--disable-symlinks-following"');
	});

	it('rejects multiple entry files', () => {
		const multiple = run([entryPath, entryPath]);
		expect(multiple.code).toBe(1);
		expect(multiple.stderr).toContain('Multiple entry files are not supported');
	});

	it('rejects --silent together with --verbose', () => {
		const { code, stderr } = run([entryPath, '--silent', '--verbose']);

		expect(code).toBe(1);
		expect(stderr).toContain('Cannot use both --silent and --verbose');
	});
});
